/**
 * pnpm pdf:build --work .work/book --out dist/book.epub [options]
 *
 * Consumes the Python `pdf2epub extract` bundle, sanitises every fragment with
 * the same whitelist used by the rest of the site, assembles an EPUB 3.3 file,
 * and runs the site's structural validator before writing it.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, join, resolve } from "node:path";
import { parseArgs } from "node:util";
import { parseHTML } from "linkedom";
import { buildEpub, type EpubAsset, type EpubSection, type EpubTocEntry } from "../../src/lib/epub/build.ts";
import { bookCss } from "../../src/lib/epub/css.ts";
import { serializeXhtml } from "../../src/lib/epub/xhtml.ts";
import { validateEpub } from "../../src/lib/epub/validate.ts";
import { generateCover, enhanceCover } from "./cover.ts";

const root = resolve(import.meta.dirname, "../..");

type Bundle = {
  format: string;
  version: number;
  pipeline: { ocrModel?: string | null; ocrDpi?: number };
  source: { sha256: string; pages: number; bytes: number };
  meta: {
    identifier: string;
    title: string;
    titleEn?: string;
    subtitle?: string;
    author: string;
    authorEn?: string;
    authorSort?: string;
    language: string;
    publisher?: string;
    firstPublished?: number;
    sourceUrl?: string;
    sourceName?: string;
    rights?: string;
    license?: string;
    licenseUrl?: string;
    description?: string;
    subjects?: string[];
    modified: string;
    ocrModel?: string;
  };
  cover: {
    kind: "original" | "generated" | "none";
    file?: string;
    width?: number;
    height?: number;
    sourcePage?: number;
    reason?: string;
  };
  sections: { id: string; label: string; file: string; epubType?: string; part?: string | null }[];
  images: { id: string; file: string; mediaType: string; alt: string; width: number; height: number; sha1: string }[];
  toc: EpubTocEntry[];
  pageList: { label: string; href: string }[];
  report: { stats: Record<string, unknown>; warnings: string[] };
};

const { values: args } = parseArgs({
  // Tolerate `--` separators that pnpm forwards between a script and its flags.
  args: process.argv.slice(2).filter((value) => value !== "--"),
  options: {
    work: { type: "string" },
    out: { type: "string" },
    title: { type: "string" },
    author: { type: "string" },
    "title-en": { type: "string" },
    "author-en": { type: "string" },
    subtitle: { type: "string" },
    cover: { type: "string", default: "auto" },
    "no-fonts": { type: "boolean", default: false },
    json: { type: "boolean", default: false },
  },
});

if (!args.work) {
  console.error("usage: pnpm pdf:build --work <bundle-dir> --out <book.epub>");
  process.exit(2);
}

const work = resolve(args.work);
const out = resolve(args.out ?? join(work, "book.epub"));
const manifestPath = join(work, "book.json");
if (!existsSync(manifestPath)) {
  console.error(`error: ${manifestPath} not found — run pdf2epub extract first`);
  process.exit(2);
}
const bundle = JSON.parse(readFileSync(manifestPath, "utf8")) as Bundle;
if (bundle.format !== "openbanglabooks-book-bundle") {
  console.error(`error: unsupported bundle format: ${bundle.format}`);
  process.exit(2);
}

const meta = {
  ...bundle.meta,
  title: args.title ?? bundle.meta.title,
  author: args.author ?? bundle.meta.author,
  titleEn: args["title-en"] ?? bundle.meta.titleEn,
  authorEn: args["author-en"] ?? bundle.meta.authorEn,
  subtitle: args.subtitle ?? bundle.meta.subtitle,
};

// Fragments are sanitised here, not trusted from Python. External links are
// allowed because this bundle is generated by us (colophon source/licence);
// ingested Wikisource content uses the default, link-free mode.
const sections: EpubSection[] = bundle.sections.map((s) => {
  const file = safeJoin(work, s.file);
  const raw = readFileSync(file, "utf8");
  return {
    id: s.id,
    label: s.label,
    xhtml: sanitize(raw),
    epubType: s.epubType,
    part: s.part ?? undefined,
  };
});

const assets: EpubAsset[] = [];
// Only ship images a chapter still references after sanitising. Extracted
// figures can disappear when a page is dropped (for example a scanned cover
// that became the generated cover), and orphan files bloat the EPUB.
const referencedImages = new Set<string>();
for (const section of sections) {
  for (const match of section.xhtml.matchAll(/(?:\.\.\/)?(images\/[A-Za-z0-9._-]+)/g)) {
    referencedImages.add(match[1]);
  }
}
for (const image of bundle.images) {
  if (!referencedImages.has(image.file)) continue;
  const file = safeJoin(work, image.file);
  if (!existsSync(file)) continue;
  assets.push({
    id: image.id,
    href: image.file,
    mediaType: image.mediaType,
    data: new Uint8Array(readFileSync(file)),
  });
}

const useFonts = !args["no-fonts"];
let coverImageId: string | undefined;
const requestedCover = args.cover as "auto" | "original" | "generate" | "none";
if (!["auto", "original", "generate", "none"].includes(requestedCover)) {
  console.error(`error: --cover must be auto, original, generate or none (got ${args.cover})`);
  process.exit(2);
}
const coverKind = requestedCover === "auto" ? bundle.cover.kind : requestedCover;
if (coverKind !== "none") {
  const coverOut = join(work, "cover.jpg");
  const generate = async () => {
    const result = await generateCover(
      {
        title: meta.title,
        author: meta.author,
        titleEn: meta.titleEn,
        authorEn: meta.authorEn,
        subtitle: meta.subtitle,
        imprint: meta.publisher,
        edition: meta.firstPublished ? String(meta.firstPublished) : undefined,
      },
      coverOut,
    );
    if (!args.json) console.log(`cover: generated ${result.width}×${result.height}`);
  };
  try {
    if (coverKind === "original") {
      if (!bundle.cover.file) throw new Error("the bundle has no original cover");
      const src = safeJoin(work, bundle.cover.file);
      if (!existsSync(src)) throw new Error(`cover file missing: ${src}`);
      const result = await enhanceCover(src, coverOut);
      if (!args.json) console.log(`cover: original page ${bundle.cover.sourcePage ?? "?"} → ${result.width}×${result.height}`);
    } else {
      await generate();
    }
  } catch (e) {
    if (requestedCover === "original") {
      console.error(`error: ${(e as Error).message} (use --cover auto or generate)`);
      process.exit(1);
    }
    console.error(`warning: ${(e as Error).message}; generating a cover instead`);
    await generate();
  }
  const data = new Uint8Array(readFileSync(coverOut));
  assets.push({ id: "cover-image", href: "images/cover.jpg", mediaType: "image/jpeg", data });
  coverImageId = "cover-image";
}

if (useFonts) {
  const fonts: [string, string][] = [
    ["noto-serif-bengali-bengali-wght-normal.woff2", "fonts/noto-serif-bengali.woff2"],
    ["noto-serif-bengali-latin-wght-normal.woff2", "fonts/noto-serif-bengali-latin.woff2"],
    ["tiro-bangla-bengali-400-normal.woff2", "fonts/tiro-bangla.woff2"],
  ];
  for (const [from, to] of fonts) {
    const file = join(root, "public/fonts", from);
    if (!existsSync(file)) continue;
    assets.push({ id: to.replace(/[^a-z0-9]+/gi, "-"), href: to, mediaType: "font/woff2", data: new Uint8Array(readFileSync(file)) });
  }
  const license = join(root, "node_modules/@fontsource/tiro-bangla/LICENSE");
  if (existsSync(license)) {
    assets.push({
      id: "font-license",
      href: "fonts/OFL.txt",
      mediaType: "text/plain",
      data: new Uint8Array(readFileSync(license)),
    });
  }
}

const linkProblems = verifyLinks(sections, assets, bundle.toc, bundle.pageList ?? [], Boolean(coverImageId));
if (linkProblems.length) {
  console.error("EPUB link check failed:");
  for (const problem of linkProblems) console.error(`  - ${problem}`);
  process.exit(1);
}

const result = buildEpub({
  meta,
  sections,
  assets,
  toc: bundle.toc,
  pageList: bundle.pageList,
  coverImageId,
  css: bookCss({ fonts: useFonts }),
});

const report = validateEpub(result.bytes);
if (!report.ok) {
  console.error("EPUB validation failed:");
  for (const error of report.errors) console.error(`  - ${error}`);
  process.exit(1);
}

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, result.bytes);
const sidecar = `${out}.report.json`;
writeFileSync(
  sidecar,
  JSON.stringify(
    {
      epub: basename(out),
      sha256: result.sha256,
      bytes: result.bytes.byteLength,
      source: bundle.source,
      pipeline: bundle.pipeline,
      title: report.title,
      language: report.language,
      entries: report.entries,
      warnings: [...report.warnings, ...(bundle.report?.warnings ?? [])],
    },
    null,
    2,
  ) + "\n",
);

if (args.json) {
  console.log(JSON.stringify({ out, sha256: result.sha256, bytes: result.bytes.byteLength, warnings: report.warnings }, null, 2));
} else {
  console.log(`EPUB: ${out}`);
  console.log(`  sha256: ${result.sha256}`);
  console.log(`  size:   ${(result.bytes.byteLength / 1024 / 1024).toFixed(2)} MB`);
  console.log(`  title:  ${report.title ?? "?"} (${report.language ?? "?"})`);
  console.log(`  files:  ${report.entries}`);
  for (const warning of report.warnings) console.log(`  warning: ${warning}`);
  console.log(`  report: ${sidecar}`);
}

function sanitize(raw: string): string {
  const { document } = parseHTML(`<!doctype html><html><body><main>${raw}</main></body></html>`);
  const main = document.querySelector("main");
  if (!main) return "";
  return serializeXhtml(main as never, { allowExternalLinks: true }).trim();
}

function safeJoin(base: string, relative: string): string {
  const target = resolve(base, relative);
  if (!target.startsWith(base + "/")) throw new Error(`unsafe bundle path: ${relative}`);
  return target;
}

/**
 * Static link check: every local href/src in a chapter and every TOC/page-list
 * target must resolve to a file we actually write, and every fragment must
 * exist in the target chapter. EPUB validators do not usually check this.
 */
function verifyLinks(
  sections: EpubSection[],
  assets: EpubAsset[],
  toc: EpubTocEntry[],
  pageList: { label: string; href: string }[],
  hasCover: boolean,
): string[] {
  const problems: string[] = [];
  const files = new Set([
    "styles.css",
    "nav.xhtml",
    "toc.ncx",
    "content.opf",
    ...assets.map((a) => a.href),
    ...sections.map((s) => `chapters/${s.id}.xhtml`),
  ]);
  if (hasCover) files.add("cover.xhtml");
  const ids = new Map(
    sections.map((s) => [s.id, new Set([...s.xhtml.matchAll(/\bid="([^"]+)"/g)].map((m) => m[1]))]),
  );

  const normalize = (href: string): { path: string; fragment?: string } | null => {
    if (/^(?:https?:|mailto:|tel:)/i.test(href)) return null;
    const [rawPath, fragment] = href.split("#");
    let path = rawPath.replace(/^\.\//, "");
    if (path.startsWith("../")) path = path.slice(3);
    else if (!path.startsWith("chapters/")) path = `chapters/${path}`;
    if (path && !files.has(path) && !/\.(?:xhtml|html)$/.test(path) && files.has(`${path}.xhtml`)) path += ".xhtml";
    return { path, fragment };
  };

  const check = (href: string, where: string, sameSection?: string) => {
    if (!href || /^(?:https?:|mailto:|tel:)/i.test(href)) return;
    if (href.startsWith("#")) {
      const id = href.slice(1);
      if (sameSection && !ids.get(sameSection)?.has(id)) problems.push(`${where}: missing anchor #${id}`);
      return;
    }
    const target = normalize(href);
    if (!target) return;
    if (!files.has(target.path)) {
      problems.push(`${where}: missing file ${href}`);
      return;
    }
    if (target.fragment) {
      const sectionId = target.path.replace(/^chapters\//, "").replace(/\.xhtml$/, "");
      if (!ids.get(sectionId)?.has(target.fragment)) {
        problems.push(`${where}: missing anchor #${target.fragment} in ${target.path}`);
      }
    }
  };

  for (const section of sections) {
    for (const match of section.xhtml.matchAll(/\b(?:href|src)="([^"]+)"/g)) {
      check(match[1], `chapter ${section.id}`, section.id);
    }
  }
  const walk = (entries: EpubTocEntry[]) => {
    for (const entry of entries) {
      check(entry.href, `TOC “${entry.label}”`);
      if (entry.children) walk(entry.children);
    }
  };
  walk(toc);
  for (const page of pageList) check(page.href, `page list “${page.label}”`);
  return problems;
}
