/**
 * Copies the self-hosted Bengali font subsets from @fontsource into
 * public/fonts and generates two @font-face sheets:
 *
 *  - src/styles/fonts.css           app chrome (font-display: swap)
 *  - src/lib/reader/font-faces.ts   injected into EPUB iframes (font-display: block,
 *                                   so the reader never paginates with a fallback face)
 *
 * Only Bengali + Latin (+ Latin Extended) subsets are shipped. Files are
 * content-stable, so they can be served with immutable caching.
 *
 * Run: pnpm fonts
 */
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "../..");
const nm = join(root, "node_modules");
const outDir = join(root, "public/fonts");

type Source = {
  /** CSS files inside node_modules to read @font-face rules from */
  css: string[];
  /** Family name to emit (normalises "… Variable" names) */
  family: string;
};

const sources: Source[] = [
  {
    family: "Hind Siliguri",
    css: ["400", "500", "600"].map((w) => `@fontsource/hind-siliguri/${w}.css`),
  },
  {
    family: "Tiro Bangla",
    css: ["@fontsource/tiro-bangla/400.css", "@fontsource/tiro-bangla/400-italic.css"],
  },
  {
    family: "Noto Serif Bengali",
    css: ["@fontsource-variable/noto-serif-bengali/wght.css"],
  },
  {
    family: "Anek Bangla",
    css: ["@fontsource-variable/anek-bangla/wght.css"],
  },
];

const FACE = /@font-face\s*{[^}]*}/g;

function rewrite(rule: string, cssPath: string, family: string, display: string) {
  const urlMatch = rule.match(/url\(\.\/files\/([^)]+\.woff2)\)\s*format\('([^']+)'\)/);
  if (!urlMatch) throw new Error(`No woff2 source in ${cssPath}`);
  const [, file, format] = urlMatch;
  const from = join(nm, dirname(cssPath), "files", file);
  copyFileSync(from, join(outDir, file));
  const get = (prop: string) => rule.match(new RegExp(`${prop}:\\s*([^;]+);`))?.[1].trim();
  return [
    "@font-face {",
    `  font-family: '${family}';`,
    `  font-style: ${get("font-style") ?? "normal"};`,
    `  font-display: ${display};`,
    `  font-weight: ${get("font-weight") ?? "400"};`,
    `  src: url(/fonts/${file}) format('${format}');`,
    `  unicode-range: ${get("unicode-range")};`,
    "}",
  ].join("\n");
}

mkdirSync(outDir, { recursive: true });
const ui: string[] = [];
const reader: string[] = [];

for (const { css, family } of sources) {
  for (const cssPath of css) {
    const text = readFileSync(join(nm, cssPath), "utf8");
    for (const rule of text.match(FACE) ?? []) {
      // Skip Vietnamese/Devanagari etc. – we only need Bengali and Latin.
      if (!/(bengali|latin)/.test(rule)) continue;
      ui.push(rewrite(rule, cssPath, family, "swap"));
      reader.push(rewrite(rule, cssPath, family, "block"));
    }
  }
}

const banner = "/* Generated by scripts/fonts/sync-fonts.ts – do not edit. */\n";
mkdirSync(join(root, "src/styles"), { recursive: true });
mkdirSync(join(root, "src/lib/reader"), { recursive: true });
writeFileSync(join(root, "src/styles/fonts.css"), banner + ui.join("\n\n") + "\n");
writeFileSync(
  join(root, "src/lib/reader/font-faces.ts"),
  `${banner}export const READER_FONT_FACES = ${JSON.stringify(reader.join("\n"))};\n`,
);
console.log(`fonts: ${ui.length} faces → public/fonts, src/styles/fonts.css, src/lib/reader/font-faces.ts`);
